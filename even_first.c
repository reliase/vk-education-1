/*
 * Дан неотсортированный массив целых чисел.
 * Необходимо перенести в начало массива все чётные числа, сохраняя их
 * относительный порядок.
 */
#include <stdio.h>
void even_first(int *arr, int n);
void swap(int *a, int *b);
int main(void){
    int arr[] = {3, 2, 4, 1, 11, 8, 9};
    int n = sizeof(arr) / sizeof(arr[0]);
    int i;

    even_first(arr, n);

    for (i = 0; i < n; i++){
        printf("%d ", arr[i]);
    }
    printf("\n");

    return 0;
}
void swap(int *a, int *b) {
    int tmp = *a;
    *a = *b;
    *b = tmp;
}
void even_first(int *arr, int n){
    int u1 =0, u2=0;
    while (u2<n){
        if (arr[u2]%2==0){
            swap (&arr[u1], &arr[u2]);
            u1++;
        }
        u2++;
    }

}

/*
 * Почему сохраняется порядок чётных:
 *   u2 идёт по массиву слева направо и встречает чётные числа в их
 *   исходном порядке. Каждое найденное чётное ставится на позицию u1,
 *   а u1 после этого растёт на 1. Значит первое чётное попадает в arr[0],
 *   второе — в arr[1] и т.д., ровно в том порядке, в каком они шли.
 *   Уже поставленные чётные стоят левее u1 и больше не трогаются.
 *   (Порядок нечётных при обменах может меняться — по условию это не важно.)
 *
 * Время: O(n) — один проход u2 по массиву, каждый шаг O(1).
 * Память: O(1) — только индексы u1, u2 и tmp в swap.
 */
